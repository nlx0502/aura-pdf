type LucideLike = ComponentType<SVGProps<SVGSVGElement> & { size?: number | string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean }>;

export interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number;
  strokeWidth?: number;
}

function wrap(C: LucideLike) {
  const Wrapped = ({ size = 16, strokeWidth = 1.5, ...rest }: IconProps) => (
    <C size={size} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" className="i" {...rest} />
  );
  return Wrapped;
}

